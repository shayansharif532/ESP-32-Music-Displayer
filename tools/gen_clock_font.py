#!/usr/bin/env python3
"""Generates firmware/components/idle_screen/font_clock.c: a large, digits-only LVGL font (0-9 and ':') for the idle screen's clock.

LVGL's built-in Montserrat stops at 48 px, which is too small for a clock that is the main element of a 480x480 screen. This
renders the same typeface (Montserrat Medium, SIL Open Font License 1.1 - the TTF ships inside LVGL's own repository) at a large
size, 4 bits per pixel, as a normal LVGL "fmt_txt" font. The digits are made tabular (every digit has the same advance), so the
time never jitters when a digit changes.

    tools\\venv\\Scripts\\python.exe tools\\gen_clock_font.py [--size 128] [--ttf PATH] [--out PATH]
"""
import argparse
import os

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DEFAULT_TTF = os.path.join(ROOT, "firmware", "managed_components", "lvgl__lvgl", "scripts", "built_in_font", "Montserrat-Medium.ttf")
DEFAULT_OUT = os.path.join(ROOT, "firmware", "components", "idle_screen", "font_clock.c")
CHARS = "0123456789:"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--size", type=int, default=128, help="font size in pixels (default %(default)s)")
    ap.add_argument("--ttf", default=DEFAULT_TTF)
    ap.add_argument("--out", default=DEFAULT_OUT)
    args = ap.parse_args()

    font = ImageFont.truetype(args.ttf, args.size)
    ascent, descent = font.getmetrics()
    digit_adv = max(font.getlength(c) for c in "0123456789")

    glyphs = []          # (adv_w x16, box_w, box_h, ofs_x, ofs_y, bytes)
    bitmap = bytearray()
    for ch in CHARS:
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")           # relative to the baseline origin; y grows downwards
        w, h = x1 - x0, y1 - y0
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        adv = digit_adv if ch.isdigit() else font.getlength(ch)
        ofs_x = round(x0 + (adv - font.getlength(ch)) / 2) if ch.isdigit() else x0   # centre a digit inside the shared advance
        px = [round(v * 15 / 255) for v in img.tobytes()]
        packed = bytearray()
        for i in range(0, len(px), 2):
            hi = px[i]
            lo = px[i + 1] if i + 1 < len(px) else 0
            packed.append((hi << 4) | lo)
        glyphs.append((round(adv * 16), w, h, ofs_x, -y1, len(bitmap)))
        bitmap += packed

    lines = []
    add = lines.append
    add("/* GENERATED by tools/gen_clock_font.py - do not edit by hand.")
    add(f" * Large clock digits (0-9 and ':') for the idle screen: Montserrat Medium {args.size} px, 4 bpp, tabular digits.")
    add(" * Montserrat is (c) Julieta Ulanovsky et al., SIL Open Font License 1.1 (see firmware/NOTICE.md). */")
    add('#include "lvgl.h"')
    add("")
    add("static const uint8_t glyph_bitmap[] = {")
    for i in range(0, len(bitmap), 16):
        add("    " + ", ".join(f"0x{b:02x}" for b in bitmap[i:i + 16]) + ",")
    add("};")
    add("")
    add("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    add("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id = 0 reserved */,")
    for ch, (adv16, w, h, ox, oy, idx) in zip(CHARS, glyphs):
        add(f"    {{.bitmap_index = {idx}, .adv_w = {adv16}, .box_w = {w}, .box_h = {h}, .ofs_x = {ox}, .ofs_y = {oy}}}, /* '{ch}' */")
    add("};")
    add("")
    add("static const lv_font_fmt_txt_cmap_t cmaps[] = {")
    add("    {")
    add(f"        .range_start = {ord(CHARS[0])}, .range_length = {len(CHARS)}, .glyph_id_start = 1,")
    add("        .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY")
    add("    },")
    add("};")
    add("")
    add("static const lv_font_fmt_txt_dsc_t font_dsc = {")
    add("    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps, .kern_dsc = NULL, .kern_scale = 0,")
    add("    .cmap_num = 1, .bpp = 4, .kern_classes = 0, .bitmap_format = 0,")
    add("};")
    add("")
    add("const lv_font_t idle_font_clock = {")
    add("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,")
    add("    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,")
    add(f"    .line_height = {ascent + descent},")
    add(f"    .base_line = {descent},")
    add("    .subpx = LV_FONT_SUBPX_NONE,")
    add("    .underline_position = -4,")
    add("    .underline_thickness = 4,")
    add("    .dsc = &font_dsc,")
    add("};")
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {args.out}: {len(bitmap)} bitmap bytes, line height {ascent + descent}, digit advance {digit_adv:.1f} px")
    for ch, (adv16, w, h, ox, oy, idx) in zip(CHARS, glyphs):
        print(f"  '{ch}' adv {adv16 / 16:.1f} box {w}x{h} ofs ({ox},{oy})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
