<#
.SYNOPSIS
  Creates firmware\secrets.local.h (git-ignored) with TEMPORARY developer Wi-Fi credentials for the dev firmware.

.DESCRIPTION
  Asks for the Wi-Fi name and the Wi-Fi password (typed hidden) and writes firmware\secrets.local.h.
  The values stay on this computer: the file is git-ignored and the password is never echoed or logged.
  Press Enter at a prompt to keep the value that is already in the file. Run again any time to change a value.

  Run it with:  powershell -NoProfile -ExecutionPolicy Bypass -File .\tools\set-dev-secrets.ps1
#>
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$out  = Join-Path $root 'firmware\secrets.local.h'

function Get-Existing([string]$name) {
    if (-not (Test-Path -LiteralPath $out)) { return '' }
    $m = Select-String -LiteralPath $out -Pattern ('^\s*#define\s+' + $name + '\s+"((?:[^"\\]|\\.)*)"') | Select-Object -First 1
    if (-not $m) { return '' }
    return ($m.Matches[0].Groups[1].Value -replace '\\"', '"' -replace '\\\\', '\')
}
function Escape-C([string]$s) { return ($s -replace '\\', '\\' -replace '"', '\"') }

$ssid = Get-Existing 'DEV_WIFI_SSID'
$pass = Get-Existing 'DEV_WIFI_PASSWORD'
$host_ip = Get-Existing 'DEV_COMPANION_HOST'

Write-Host ''
Write-Host 'Developer Wi-Fi settings for the desk display (stored only in firmware\secrets.local.h, git-ignored).'
Write-Host 'The board has a 2.4 GHz radio only: use a 2.4 GHz network.'
Write-Host ''

$in = Read-Host ('Wi-Fi name (SSID)' + $(if ($ssid) { " [Enter = keep '$ssid']" } else { '' }))
if ($in) { $ssid = $in }

$sec = Read-Host ('Wi-Fi password (typing is hidden)' + $(if ($pass) { ' [Enter = keep current]' } else { '' })) -AsSecureString
$bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($sec)
try { $plain = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr) } finally { [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr) }
if ($plain) { $pass = $plain }

$in = Read-Host ('PC address, only if automatic discovery fails (usually leave empty)' + $(if ($host_ip) { " [Enter = keep '$host_ip']" } else { '' }))
if ($in) { $host_ip = $in.Trim() }

$text = @"
#pragma once
/* Generated by tools\set-dev-secrets.ps1 - git-ignored, never commit. */
#define DEV_WIFI_SSID           "$(Escape-C $ssid)"
#define DEV_WIFI_PASSWORD       "$(Escape-C $pass)"
#define DEV_COMPANION_HOST      "$(Escape-C $host_ip)"
"@
[IO.File]::WriteAllText($out, $text + "`n", (New-Object Text.UTF8Encoding($false)))

Write-Host ''
Write-Host "Saved $out"
Write-Host ("  Wi-Fi name : {0}" -f $(if ($ssid) { $ssid } else { '(empty)' }))
Write-Host ("  Wi-Fi pass : {0}" -f $(if ($pass) { ('*' * [Math]::Min($pass.Length, 12)) + " ($($pass.Length) characters)" } else { '(empty)' }))
Write-Host ("  PC address : {0}" -f $(if ($host_ip) { $host_ip } else { '(automatic)' }))
Write-Host ''
Write-Host 'Done. You can close this tab.'
