<#
.SYNOPSIS
  Creates firmware\secrets.local.h (git-ignored) with TEMPORARY developer credentials for the dev firmware.

.DESCRIPTION
  Asks for the Wi-Fi name, the Wi-Fi password (typed hidden) and the Spotify Client ID, and writes
  firmware\secrets.local.h. The values stay on this computer: the file is git-ignored and the password is never
  echoed or logged. Press Enter at a prompt to keep the value that is already in the file.
  Run again any time to change a value.
#>
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$out  = Join-Path $root 'firmware\secrets.local.h'

function Get-Existing([string]$name) {
    if (-not (Test-Path -LiteralPath $out)) { return '' }
    $m = Select-String -LiteralPath $out -Pattern ('^\s*#define\s+' + $name + '\s+"((?:[^"\\]|\\.)*)"') | Select-Object -First 1
    if (-not $m) { return '' }
    return ($m.Matches[0].Groups[1].Value -replace '\\"', '"' -replace '\\\\', '\')
}
function Escape-C([string]$s) { return ($s -replace '\\', '\\' -replace '"', '\"') }

$ssid = Get-Existing 'DEV_WIFI_SSID'
$pass = Get-Existing 'DEV_WIFI_PASSWORD'
$cid  = Get-Existing 'DEV_SPOTIFY_CLIENT_ID'

Write-Host ''
Write-Host 'Developer credentials for the Spotify desk display (stored only in firmware\secrets.local.h, git-ignored).'
Write-Host 'The board has a 2.4 GHz radio only: use a 2.4 GHz network.'
Write-Host ''

$in = Read-Host ('Wi-Fi name (SSID)' + $(if ($ssid) { " [Enter = keep '$ssid']" } else { '' }))
if ($in) { $ssid = $in }

$sec = Read-Host ('Wi-Fi password (typing is hidden)' + $(if ($pass) { ' [Enter = keep current]' } else { '' })) -AsSecureString
$bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($sec)
try { $plain = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr) } finally { [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr) }
if ($plain) { $pass = $plain }

$in = Read-Host ('Spotify Client ID (32 characters; leave empty if you have not created the Spotify app yet)' + $(if ($cid) { " [Enter = keep '$cid']" } else { '' }))
if ($in) { $cid = $in.Trim() }
if ($cid -and $cid -notmatch '^[0-9a-fA-F]{32}$') {
    Write-Warning 'That does not look like a Spotify Client ID (expected 32 hex characters). Saved anyway - run this script again to fix it.'
}

$text = @"
#pragma once
/* Generated by tools\set-dev-secrets.ps1 - git-ignored, never commit. */
#define DEV_WIFI_SSID           "$(Escape-C $ssid)"
#define DEV_WIFI_PASSWORD       "$(Escape-C $pass)"
#define DEV_SPOTIFY_CLIENT_ID   "$(Escape-C $cid)"
"@
[IO.File]::WriteAllText($out, $text + "`n", (New-Object Text.UTF8Encoding($false)))

Write-Host ''
Write-Host "Saved $out"
Write-Host ("  Wi-Fi name : {0}" -f $(if ($ssid) { $ssid } else { '(empty)' }))
Write-Host ("  Wi-Fi pass : {0}" -f $(if ($pass) { ('*' * [Math]::Min($pass.Length, 12)) + " ($($pass.Length) characters)" } else { '(empty)' }))
Write-Host ("  Client ID  : {0}" -f $(if ($cid) { $cid } else { '(empty)' }))
Write-Host ''
Write-Host 'Done. You can close this tab and tell Claude it is saved.'
