#!/usr/bin/env python3
"""Generates firmware/components/idle_screen/idle_date_vectors.inc from the shared test vectors of the idle screen's date
(companion/tests/data/idle_date_vectors.json), so the on-target self-test checks the C code against the same expectations as the
companion's unit tests.

    python tools/gen_date_vectors.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "companion", "tests", "data", "idle_date_vectors.json")
DST = os.path.join(ROOT, "firmware", "components", "idle_screen", "idle_date_vectors.inc")
FORMATS = ("mon_d_y", "d_mon_y", "mdy", "dmy")


def main() -> int:
    with open(SRC, encoding="utf-8") as f:
        vectors = json.load(f)
    lines = ["/* Generated by tools/gen_date_vectors.py from companion/tests/data/idle_date_vectors.json - do not edit. */",
             "static const vec_t VECTORS[] = {"]
    for v in vectors:
        fm = ", ".join('"%s"' % v["formats"][k] for k in FORMATS)
        lines.append("    { %dLL, %d, %d, %d, { %s } }," % (v["clock_ms"], v["year"], v["month"], v["day"], fm))
    lines.append("};")
    with open(DST, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", DST, len(vectors), "vectors")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
