#define BG_BYTES            (SCR * SCR * 2)
#define RGB_BYTES           (SCR * SCR * 3)

#define NVS_NS              "idle"
#define NVS_KEY             "cfg"
#define CFG_MAGIC           0x49444C32U               /* "IDL2": IDL1 + the date options (an IDL1 blob is migrated, see nvs_load_cfg) */
#define CFG_MAGIC_V1        0x49444C31U
#define PART_LABEL          "idle_img"
#define PART_SUBTYPE        0x40
#define IMG_MAGIC           0x31494449U               /* "IDI1" */
#define IMG_HDR_SIZE        4096                      /* the first flash sector holds the header, the JPEG follows */
#define IMG_MAX_BYTES       (300 * 1024)
#define TEXT_MAX            40
#define DELAY_MIN_S         2
#define DELAY_MAX_S         60
#define DELAY_DEFAULT_S     4

#define DEFAULT_ACCENT      0x4DA3FF
#define CLOCK_H             idle_font_clock.line_height
#define CLOCK_ASCENT        (idle_font_clock.line_height - idle_font_clock.base_line)
#define CLOCK_DIGIT_MID     (CLOCK_ASCENT - 46)       /* vertical middle of a digit, measured from the top of the clock label */

enum { TH_MINIMAL, TH_DARK, TH_NEON, TH_PHOTO };

typedef struct {                                      /* what is kept in NVS (and compared with the companion's answer) */
    uint32_t magic;
    uint32_t version;                                 /* the companion's settings version this was made from */
    uint32_t accent;                                  /* 0xRRGGBB */
    uint32_t img_crc, img_size;                       /* the background picture (size 0 = none) */
    uint16_t delay_s;
    uint8_t theme, bg_mode, show_clock, clock_24h;
    uint8_t show_date, date_fmt;                      /* IDLE_DATE_FMT_* */
    char text[TEXT_MAX + 1];
} idle_cfg_t;

typedef struct {                                      /* the stored layout of the first release (IDL1) */
    uint32_t magic, version, accent, img_crc, img_size;
    uint16_t delay_s;
    uint8_t theme, bg_mode, show_clock, clock_24h;
    char text[TEXT_MAX + 1];
} idle_cfg_v1_t;

typedef struct {                                      /* first sector of the idle_img partition */
    uint32_t magic, size, crc;
    uint16_t w, h;
} img_hdr_t;

