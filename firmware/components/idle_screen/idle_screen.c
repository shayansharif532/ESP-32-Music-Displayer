bool idle_screen_have_version(uint32_t version)
{
    if (!s.work || xSemaphoreTake(s.work, pdMS_TO_TICKS(4000)) != pdTRUE) {
        return true;                                      /* still loading: do not start a sync now */
    }
    const bool have = s.loaded && s.cfg.version == version;
    xSemaphoreGive(s.work);
    return have;
}

static bool parse_config(const char *json, size_t len, idle_cfg_t *n)
{
    cJSON *j = cJSON_ParseWithLength(json, len);
    if (!j) {
        return false;
    }
    bool ok = false;
    const cJSON *ver = cJSON_GetObjectItemCaseSensitive(j, "version");
    if (cJSON_IsTrue(cJSON_GetObjectItemCaseSensitive(j, "ok")) && cJSON_IsNumber(ver) && ver->valuedouble >= 1) {
        cfg_defaults(n);
        n->version = (uint32_t)ver->valuedouble;
        const cJSON *v = cJSON_GetObjectItemCaseSensitive(j, "theme");
        if (cJSON_IsString(v)) {
            n->theme = !strcmp(v->valuestring, "minimal") ? TH_MINIMAL : !strcmp(v->valuestring, "neon") ? TH_NEON :
                       !strcmp(v->valuestring, "photo") ? TH_PHOTO : TH_DARK;
        }
        v = cJSON_GetObjectItemCaseSensitive(j, "accent");
        if (cJSON_IsString(v) && strlen(v->valuestring) == 7 && v->valuestring[0] == '#') {
            char *end = NULL;
            unsigned long rgb = strtoul(v->valuestring + 1, &end, 16);
            if (end && *end == '\0') {
                n->accent = (uint32_t)rgb & 0xFFFFFF;
            }
        }
        v = cJSON_GetObjectItemCaseSensitive(j, "clock");
        n->show_clock = cJSON_IsFalse(v) ? 0 : 1;
        v = cJSON_GetObjectItemCaseSensitive(j, "clock_24h");
        n->clock_24h = cJSON_IsFalse(v) ? 0 : 1;
        v = cJSON_GetObjectItemCaseSensitive(j, "date");                    /* an older companion sends none: the date defaults to shown */
        n->show_date = cJSON_IsFalse(v) ? 0 : 1;
        v = cJSON_GetObjectItemCaseSensitive(j, "date_fmt");
        n->date_fmt = (cJSON_IsNumber(v) && v->valuedouble >= 0 && v->valuedouble < IDLE_DATE_FMT_COUNT) ? (uint8_t)v->valuedouble : IDLE_DATE_FMT_MON_D_Y;
        v = cJSON_GetObjectItemCaseSensitive(j, "delay_s");
        if (cJSON_IsNumber(v)) {
            n->delay_s = (uint16_t)clampi((int)v->valuedouble, DELAY_MIN_S, DELAY_MAX_S);
        }
        v = cJSON_GetObjectItemCaseSensitive(j, "bg_mode");
        n->bg_mode = cJSON_IsString(v) ? (!strcmp(v->valuestring, "fit") ? 1 : !strcmp(v->valuestring, "blur") ? 2 : 0) : 0;
        v = cJSON_GetObjectItemCaseSensitive(j, "text");
        if (cJSON_IsString(v)) {                          /* printable ASCII only: the display fonts have nothing else */
            size_t o = 0;
            for (const unsigned char *p = (const unsigned char *)v->valuestring; *p && o < TEXT_MAX; p++) {
                if (*p >= 0x20 && *p < 0x7F) {
                    n->text[o++] = (char)*p;
                }
            }
            n->text[o] = '\0';
        }
        const cJSON *img = cJSON_GetObjectItemCaseSensitive(j, "image");
        if (cJSON_IsObject(img)) {
            const cJSON *sz = cJSON_GetObjectItemCaseSensitive(img, "size"), *crc = cJSON_GetObjectItemCaseSensitive(img, "crc");
            if (cJSON_IsNumber(sz) && cJSON_IsNumber(crc) && sz->valuedouble > 100 && sz->valuedouble <= IMG_MAX_BYTES) {
                n->img_size = (uint32_t)sz->valuedouble;
                n->img_crc = (uint32_t)crc->valuedouble;
            }
        }
        ok = true;
    }
    cJSON_Delete(j);
    return ok;
}

/* The new config is final (picture, if any, is in place): remember it and redraw. work lock held. */
static void finish_apply(const idle_cfg_t *n)
{
    s.cfg = *n;
    nvs_save_cfg(&s.cfg);
    rebuild_theme();
    ESP_LOGI(TAG, "idle settings version %u applied (theme %u, %s clock, date %s/%u, %s)", (unsigned)n->version, (unsigned)n->theme,
             n->show_clock ? (n->clock_24h ? "24h" : "12h") : "no", n->show_date ? "on" : "off", (unsigned)n->date_fmt, n->img_size ? "picture" : "no picture");
}

int idle_screen_apply_config(const char *json, size_t len)
{
    if (!s.work || xSemaphoreTake(s.work, pdMS_TO_TICKS(5000)) != pdTRUE) {
        return -1;
    }
    idle_cfg_t n;
    int rc = -1;
    if (!parse_config(json, len, &n)) {
        ESP_LOGW(TAG, "unusable idle settings from the companion");
    } else {
        const bool same_pic = n.img_size && n.img_size == s.cfg.img_size && n.img_crc == s.cfg.img_crc && s.photo_px;
        const bool known_bad = n.img_size && n.img_crc == s.photo_failed_crc;
        if (n.img_size && !same_pic && !known_bad) {
            s.pending = n;
            s.pending_valid = true;
            rc = 1;                                       /* the picture comes next */
        } else {
            uint16_t *old = NULL;
            if (!n.img_size) {                            /* no picture any more */
                if (s.cfg.img_size) {
                    img_invalidate();
                }
                old = s.photo_px;
                s.photo_px = NULL;
            }
            finish_apply(&n);                             /* (a known-undecodable picture is not downloaded again: Dark theme) */
            heap_caps_free(old);
            rc = 0;
        }
    }
    xSemaphoreGive(s.work);
    return rc;
}

bool idle_screen_apply_picture(const uint8_t *jpeg, size_t len)
{
    if (!s.work || xSemaphoreTake(s.work, pdMS_TO_TICKS(5000)) != pdTRUE) {
        return false;
    }
    bool ok = false;
    if (s.pending_valid) {
        idle_cfg_t n = s.pending;
        s.pending_valid = false;
        if (len != n.img_size || crc32_of(jpeg, len) != n.img_crc) {
            ESP_LOGW(TAG, "picture does not match its description (%u bytes, expected %u): will retry", (unsigned)len, (unsigned)n.img_size);
        } else {
            uint16_t *photo = decode_photo(jpeg, len);
            uint16_t *old = s.photo_px;
            if (photo) {
                if (!img_store(jpeg, len, n.img_crc)) {
                    ESP_LOGW(TAG, "could not store the picture in flash: it is shown now but will be fetched again after a reboot");
                    img_invalidate();
                }
                s.photo_px = photo;
                s.photo_failed_crc = 0;
            } else {
                ESP_LOGW(TAG, "the picture cannot be decoded: falling back to the built-in theme");
                img_invalidate();
                s.photo_px = NULL;
                s.photo_failed_crc = n.img_crc;
            }
            finish_apply(&n);
            heap_caps_free(old);
            ok = true;
        }
    }
    xSemaphoreGive(s.work);
    return ok;
}
