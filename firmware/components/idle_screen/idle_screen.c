static void inert(lv_obj_t *o)
{
    lv_obj_remove_flag(o, LV_OBJ_FLAG_CLICKABLE | LV_OBJ_FLAG_SCROLLABLE);
}

static lv_obj_t *mk_label(const lv_font_t *font, uint32_t colour)
{
    lv_obj_t *l = lv_label_create(s.scr);
    lv_obj_set_style_text_font(l, font, 0);
    lv_obj_set_style_text_color(l, lv_color_hex(colour), 0);
    inert(l);
    return l;
}

static void on_tap(lv_event_t *e)
{
    (void)e;
    if (s.tap) {
        s.tap(s.tap_ctx);
    }
}

static uint8_t effective_theme(void)
{
    if (s.cfg.theme == TH_PHOTO) {
        return s.photo_px ? TH_PHOTO : TH_DARK;           /* no usable picture: the built-in Dark theme */
    }
    return s.cfg.theme;
}

/* Colours, layout and the background for the current config. LVGL lock held. `new_bg` = a generated background for a built-in theme
 * (ownership passes here), NULL for the Photo theme. */
static void commit_theme(uint16_t *new_bg, uint8_t eff)
{
    uint16_t *old_bg = s.bg_px;
    if (eff == TH_PHOTO) {
        lv_image_set_src(s.bg, next_dsc(s.photo_px));
        lv_obj_remove_flag(s.dim, LV_OBJ_FLAG_HIDDEN);
        s.bg_px = NULL;
        heap_caps_free(new_bg);
    } else if (new_bg) {
        lv_image_set_src(s.bg, next_dsc(new_bg));
        lv_obj_add_flag(s.dim, LV_OBJ_FLAG_HIDDEN);
        s.bg_px = new_bg;
    } else {
        return;                                           /* no memory for a new background: keep what is shown */
    }
    heap_caps_free(old_bg);

    const uint32_t acc = s.cfg.accent;
    const bool clock = s.cfg.show_clock, text = s.cfg.text[0] != '\0', date = s.cfg.show_date != 0;
    const bool neon = eff == TH_NEON, photo = eff == TH_PHOTO, minimal = eff == TH_MINIMAL;

    lv_obj_set_style_bg_color(s.dot, lv_color_hex(acc), 0);
    lv_obj_set_style_bg_color(s.line, lv_color_hex(acc), 0);
    lv_obj_set_style_shadow_width(s.line, neon ? 16 : 0, 0);
    lv_obj_set_style_shadow_color(s.line, lv_color_hex(acc), 0);
    lv_obj_set_style_shadow_opa(s.line, LV_OPA_60, 0);
    if (minimal) {
        lv_obj_add_flag(s.line, LV_OBJ_FLAG_HIDDEN);
    } else {
        lv_obj_remove_flag(s.line, LV_OBJ_FLAG_HIDDEN);
    }

    /* glow (Neon) or dark outline (Photo) behind the big digits and the custom line, for legibility */
    for (int i = 0; i < 4; i++) {
        lv_obj_set_style_text_color(s.shadow[i], neon ? lv_color_hex(acc) : lv_color_black(), 0);
        lv_obj_set_style_text_opa(s.shadow[i], neon ? 46 : 110, 0);
        if (clock && (neon || photo)) {
            lv_obj_remove_flag(s.shadow[i], LV_OBJ_FLAG_HIDDEN);
        } else {
            lv_obj_add_flag(s.shadow[i], LV_OBJ_FLAG_HIDDEN);
        }
    }
    for (int i = 0; i < 4; i++) {                         /* the date gets the same treatment, a little tighter */
        lv_obj_set_style_text_color(s.dshadow[i], neon ? lv_color_hex(acc) : lv_color_black(), 0);
        lv_obj_set_style_text_opa(s.dshadow[i], neon ? 46 : 110, 0);
        if (date && (neon || photo)) {
            lv_obj_remove_flag(s.dshadow[i], LV_OBJ_FLAG_HIDDEN);
        } else {
            lv_obj_add_flag(s.dshadow[i], LV_OBJ_FLAG_HIDDEN);
        }
    }
    if (date) lv_obj_remove_flag(s.date, LV_OBJ_FLAG_HIDDEN); else lv_obj_add_flag(s.date, LV_OBJ_FLAG_HIDDEN);
    lv_obj_set_style_text_opa(s.tshadow, 130, 0);
    if (text && photo) {
        lv_obj_remove_flag(s.tshadow, LV_OBJ_FLAG_HIDDEN);
    } else {
        lv_obj_add_flag(s.tshadow, LV_OBJ_FLAG_HIDDEN);
    }

    if (clock) lv_obj_remove_flag(s.clock, LV_OBJ_FLAG_HIDDEN); else lv_obj_add_flag(s.clock, LV_OBJ_FLAG_HIDDEN);
    if (clock && !s.cfg.clock_24h) lv_obj_remove_flag(s.ampm, LV_OBJ_FLAG_HIDDEN); else lv_obj_add_flag(s.ampm, LV_OBJ_FLAG_HIDDEN);

    /* layout (480 x 480): vertical centres of the clock digits, the date and the custom line, and the top of the accent line. The same
     * numbers are in the companion's preview (idle.py), see docs/idle-screen.md. */
    int clock_cy = 0, date_cy = 0, line_y, text_cy = 0;
    const lv_font_t *text_font = (clock || date) ? &lv_font_montserrat_32 : &lv_font_montserrat_48;
    const lv_font_t *date_font = clock ? &lv_font_montserrat_26 : &lv_font_montserrat_48;
    if (date) {
        if (clock && text)      { clock_cy = 138; date_cy = 214; line_y = 252; text_cy = 300; }
        else if (clock)         { clock_cy = 172; date_cy = 252; line_y = 296; }
        else if (text)          { date_cy = 178;  line_y = 236; text_cy = 290; }
        else                    { date_cy = 215;  line_y = 262; }
    } else {
        if (clock && text)      { clock_cy = 168; line_y = 262; text_cy = 306; }
        else if (clock)         { clock_cy = 205; line_y = 300; }
        else if (text)          { text_cy = 215;  line_y = 268; }
        else                    { line_y = 240; }
    }
    lv_obj_set_style_text_font(s.text, text_font, 0);
    lv_obj_set_style_text_font(s.tshadow, text_font, 0);
    lv_label_set_text(s.text, s.cfg.text);
    lv_label_set_text(s.tshadow, s.cfg.text);
    if (text) lv_obj_remove_flag(s.text, LV_OBJ_FLAG_HIDDEN); else lv_obj_add_flag(s.text, LV_OBJ_FLAG_HIDDEN);
    const int clock_top = clock_cy - CLOCK_DIGIT_MID;
    lv_obj_align(s.clock, LV_ALIGN_TOP_MID, 0, clock_top);
    for (int i = 0; i < 4; i++) {
        lv_obj_align(s.shadow[i], LV_ALIGN_TOP_MID, RING[i][0], clock_top + RING[i][1]);
    }
    lv_obj_align(s.line, LV_ALIGN_TOP_MID, 0, line_y);
    lv_obj_set_style_text_font(s.date, date_font, 0);
    const int dh = lv_font_get_line_height(date_font);
    lv_obj_align(s.date, LV_ALIGN_TOP_MID, 0, date_cy - dh / 2);
    for (int i = 0; i < 4; i++) {
        lv_obj_set_style_text_font(s.dshadow[i], date_font, 0);
        lv_obj_align(s.dshadow[i], LV_ALIGN_TOP_MID, DRING[i][0], date_cy - dh / 2 + DRING[i][1]);
    }
    const int th = lv_font_get_line_height(text_font);
    lv_obj_align(s.text, LV_ALIGN_TOP_MID, 0, text_cy - th / 2);
    lv_obj_align(s.tshadow, LV_ALIGN_TOP_MID, 0, text_cy - th / 2 + 2);

    s.shown_clock[0] = '\0';                              /* force the clock label to be rewritten in the (possibly new) format */
    s.shown_date[0] = '\0';
    update_clock_text();
}

/* Generate the background outside the LVGL lock, then swap it in. work lock held by the caller. */
static void rebuild_theme(void)
{
    const uint8_t eff = effective_theme();
    uint16_t *bg = eff == TH_PHOTO ? NULL : make_theme_bg(eff, s.cfg.accent);
    if (eff != TH_PHOTO && !bg) {
        ESP_LOGW(TAG, "no PSRAM for the idle background");
    }
    if (!bsp_display_lock(2000)) {
        heap_caps_free(bg);
        return;
    }
    commit_theme(bg, eff);
    bsp_display_unlock();
}

/* ---- public: screen ------------------------------------------------------------------------------------------- */

static void load_task(void *arg)
{
    (void)arg;
    xSemaphoreTake(s.work, portMAX_DELAY);
    idle_cfg_t c;
    if (nvs_load_cfg(&c)) {
        s.cfg = c;
        if (c.img_size) {
            size_t len = 0;
            uint8_t *jpeg = img_load(&len, c.img_crc);
            if (jpeg) {
                s.photo_px = decode_photo(jpeg, len);
                heap_caps_free(jpeg);
            }
            if (!s.photo_px) {
                ESP_LOGW(TAG, "the stored picture cannot be shown: using the built-in theme until the companion resends it");
                s.cfg.img_crc = 0;                         /* so the next sync downloads it again ... */
                s.cfg.version = 0;                         /* ... which it only does when the version looks out of date */
            }
        }
        ESP_LOGI(TAG, "stored settings loaded: version %u, theme %u%s", (unsigned)s.cfg.version, (unsigned)s.cfg.theme, s.photo_px ? ", picture" : "");
    }
    rebuild_theme();
    s.loaded = true;
    xSemaphoreGive(s.work);
    vTaskDelete(NULL);
}

void idle_screen_init(idle_tap_cb_t on_tap_cb, void *ctx)
{
    cfg_defaults(&s.cfg);
    s.tap = on_tap_cb;
    s.tap_ctx = ctx;
    s.work = xSemaphoreCreateMutex();
    if (!s.work || !bsp_display_lock(0)) {
        return;
    }
    s.scr = lv_obj_create(NULL);
    lv_obj_set_style_bg_color(s.scr, lv_color_black(), 0);
    lv_obj_set_style_bg_opa(s.scr, LV_OPA_COVER, 0);
    lv_obj_remove_flag(s.scr, LV_OBJ_FLAG_SCROLLABLE);
    lv_obj_add_flag(s.scr, LV_OBJ_FLAG_CLICKABLE);
    lv_obj_add_event_cb(s.scr, on_tap, LV_EVENT_CLICKED, NULL);

    s.bg = lv_image_create(s.scr);
    lv_obj_set_size(s.bg, SCR, SCR);
    lv_obj_set_pos(s.bg, 0, 0);
    inert(s.bg);

    s.dim = lv_obj_create(s.scr);                         /* a photo is dimmed a little so the white clock stays readable */
    lv_obj_remove_style_all(s.dim);
    lv_obj_set_size(s.dim, SCR, SCR);
    lv_obj_set_style_bg_color(s.dim, lv_color_black(), 0);
    lv_obj_set_style_bg_opa(s.dim, LV_OPA_30, 0);
    inert(s.dim);
    lv_obj_add_flag(s.dim, LV_OBJ_FLAG_HIDDEN);

    for (int i = 0; i < 4; i++) {
        s.shadow[i] = mk_label(&idle_font_clock, 0x000000);
    }
    s.clock = mk_label(&idle_font_clock, 0xFFFFFF);
    s.ampm = mk_label(&lv_font_montserrat_26, 0xDADAE4);
    for (int i = 0; i < 4; i++) {                          /* the date: an outline / glow (Photo, Neon) behind a light label */
        s.dshadow[i] = mk_label(&lv_font_montserrat_26, 0x000000);
    }
    s.date = mk_label(&lv_font_montserrat_26, 0xE6E6EE);
    for (int i = 0; i < 5; i++) {
        lv_obj_t *l = i < 4 ? s.dshadow[i] : s.date;
        lv_obj_set_width(l, 440);
        lv_obj_set_style_text_align(l, LV_TEXT_ALIGN_CENTER, 0);
        lv_label_set_long_mode(l, LV_LABEL_LONG_MODE_CLIP);   /* never wraps: even the widest format fits 440 px at 48 px */
    }
    s.line = lv_obj_create(s.scr);
    lv_obj_remove_style_all(s.line);
    lv_obj_set_size(s.line, 64, 3);
    lv_obj_set_style_radius(s.line, LV_RADIUS_CIRCLE, 0);
    lv_obj_set_style_bg_opa(s.line, LV_OPA_COVER, 0);
    inert(s.line);
    s.tshadow = mk_label(&lv_font_montserrat_32, 0x000000);
    s.text = mk_label(&lv_font_montserrat_32, 0xF2F2F7);
    for (lv_obj_t *l = s.text; l; l = (l == s.text ? s.tshadow : NULL)) {
        lv_obj_set_width(l, 440);
        lv_obj_set_style_text_align(l, LV_TEXT_ALIGN_CENTER, 0);
        lv_label_set_long_mode(l, LV_LABEL_LONG_MODE_DOTS);
    }

    s.dot = lv_obj_create(s.scr);                         /* subtle connection state at the top: a dot + "Connected" */
    lv_obj_remove_style_all(s.dot);
    lv_obj_set_size(s.dot, 6, 6);
    lv_obj_set_style_radius(s.dot, LV_RADIUS_CIRCLE, 0);
    lv_obj_set_style_bg_opa(s.dot, LV_OPA_COVER, 0);
    lv_obj_set_pos(s.dot, 188, 20);
    inert(s.dot);
    s.conn = mk_label(&lv_font_montserrat_12, 0x8C90AA);
    lv_label_set_text(s.conn, "Connected");
    lv_obj_set_pos(s.conn, 200, 16);

    s.status = mk_label(&lv_font_montserrat_14, 0x8C90AA);
    lv_obj_set_width(s.status, 440);
    lv_obj_set_style_text_align(s.status, LV_TEXT_ALIGN_CENTER, 0);
    lv_label_set_long_mode(s.status, LV_LABEL_LONG_MODE_DOTS);
    lv_obj_align(s.status, LV_ALIGN_TOP_MID, 0, 436);
    lv_label_set_text(s.status, "Nothing playing");
    strlcpy(s.status_text, "Nothing playing", sizeof s.status_text);

    s.tick = lv_timer_create(tick_cb, 1000, NULL);
    lv_timer_pause(s.tick);
    bsp_display_unlock();

#ifdef APP_DEV_TOOLS
    {
        const char *bad = idle_date_selftest();
        if (bad) {
            ESP_LOGE(TAG, "idle date selftest FAILED: %s", bad);
        } else {
            ESP_LOGI(TAG, "idle date selftest ok");
        }
    }
#endif
    xTaskCreatePinnedToCore(load_task, "idle_load", 8192, NULL, 3, NULL, 0);
}

lv_obj_t *idle_screen_obj(void)
{
    return s.scr;
}

void idle_screen_activate(bool visible)
{
    if (!s.scr || !bsp_display_lock(1000)) {
        return;
    }
    s.active = visible;
    if (visible) {
        update_clock_text();
        lv_timer_resume(s.tick);
    } else {
        lv_timer_pause(s.tick);
    }
    bsp_display_unlock();
}

void idle_screen_set_clock(int64_t local_ms)
{
    if (local_ms <= 0) {
        return;
    }
    portENTER_CRITICAL(&s.clock_mux);
    s.clock_base_ms = local_ms - now_ms();
    if (s.clock_base_ms == 0) {
        s.clock_base_ms = 1;                              /* 0 means "never synced" */
    }
    portEXIT_CRITICAL(&s.clock_mux);
}

void idle_screen_set_status(const char *text)
{
    text = text ? text : "";
    if (!s.scr || strcmp(text, s.status_text) == 0 || !bsp_display_lock(1000)) {
        return;
    }
    strlcpy(s.status_text, text, sizeof s.status_text);
    lv_label_set_text(s.status, s.status_text);
    bsp_display_unlock();
}

uint32_t idle_screen_delay_ms(void)
{
    return (uint32_t)s.cfg.delay_s * 1000U;
}

