/* ---- small helpers ----------------------------------------------------------------------------------------- */

static inline int clampi(int v, int lo, int hi)
{
    return v < lo ? lo : (v > hi ? hi : v);
}

static int64_t now_ms(void)
{
    return esp_timer_get_time() / 1000;
}

static uint32_t crc32_of(const uint8_t *data, size_t len)
{
    return esp_rom_crc32_le(0, data, len);            /* the same value as zlib.crc32 on the PC */
}

static void cfg_defaults(idle_cfg_t *c)
{
    memset(c, 0, sizeof *c);
    c->magic = CFG_MAGIC;
    c->accent = DEFAULT_ACCENT;
    c->theme = TH_DARK;
    c->show_clock = 1;
    c->clock_24h = 1;
    c->show_date = 1;
    c->date_fmt = IDLE_DATE_FMT_MON_D_Y;
    c->delay_s = DELAY_DEFAULT_S;
}

static bool cfg_sane(const idle_cfg_t *c)
{
    return c->magic == CFG_MAGIC && c->theme <= TH_PHOTO && c->delay_s >= DELAY_MIN_S && c->delay_s <= DELAY_MAX_S &&
           c->img_size <= IMG_MAX_BYTES && c->text[TEXT_MAX] == '\0' && c->date_fmt < IDLE_DATE_FMT_COUNT && c->show_date <= 1;
}

/* ---- persistence --------------------------------------------------------------------------------------------- */

static bool nvs_load_cfg(idle_cfg_t *c)
{
    nvs_handle_t h;
    if (nvs_open(NVS_NS, NVS_READONLY, &h) != ESP_OK) {
        return false;
    }
    size_t len = 0;
    esp_err_t err = nvs_get_blob(h, NVS_KEY, NULL, &len);       /* the size says which layout was stored */
    bool ok = false;
    if (err == ESP_OK && len == sizeof *c) {
        len = sizeof *c;
        ok = nvs_get_blob(h, NVS_KEY, c, &len) == ESP_OK && len == sizeof *c && cfg_sane(c);
    } else if (err == ESP_OK && len == sizeof(idle_cfg_v1_t)) {  /* a first-release blob: keep every setting, the date gets its defaults */
        idle_cfg_v1_t old;
        len = sizeof old;
        if (nvs_get_blob(h, NVS_KEY, &old, &len) == ESP_OK && len == sizeof old && old.magic == CFG_MAGIC_V1) {
            cfg_defaults(c);
            c->version = old.version;
            c->accent = old.accent;
            c->img_crc = old.img_crc;
            c->img_size = old.img_size;
            c->delay_s = old.delay_s;
            c->theme = old.theme;
            c->bg_mode = old.bg_mode;
            c->show_clock = old.show_clock;
            c->clock_24h = old.clock_24h;
            memcpy(c->text, old.text, sizeof c->text);
            ok = cfg_sane(c);
            if (ok) {
                ESP_LOGI(TAG, "stored settings migrated from the first release layout");
            }
        }
    }
    nvs_close(h);
    return ok;
}

static void nvs_save_cfg(const idle_cfg_t *c)
{
    nvs_handle_t h;
    if (nvs_open(NVS_NS, NVS_READWRITE, &h) != ESP_OK) {
        ESP_LOGW(TAG, "cannot open NVS to store the idle settings");
        return;
    }
    if (nvs_set_blob(h, NVS_KEY, c, sizeof *c) != ESP_OK || nvs_commit(h) != ESP_OK) {
        ESP_LOGW(TAG, "storing the idle settings failed");
    }
    nvs_close(h);
}

static const esp_partition_t *img_part(void)
{
    return esp_partition_find_first(ESP_PARTITION_TYPE_DATA, (esp_partition_subtype_t)PART_SUBTYPE, PART_LABEL);
}

/* Header sector first (so an interrupted write leaves "no picture"), then the data, the header last. Sector by sector with a short
 * pause so the display refresh and Wi-Fi keep running while the flash is busy. */
static bool img_store(const uint8_t *jpeg, size_t len, uint32_t crc)
{
    const esp_partition_t *p = img_part();
    if (!p || len == 0 || len + IMG_HDR_SIZE > p->size) {
        return false;
    }
    if (esp_partition_erase_range(p, 0, IMG_HDR_SIZE) != ESP_OK) {
        return false;
    }
    const size_t data_end = (IMG_HDR_SIZE + len + 4095) & ~(size_t)4095;
    for (size_t off = IMG_HDR_SIZE; off < data_end; off += 4096) {
        size_t n = len - (off - IMG_HDR_SIZE) < 4096 ? len - (off - IMG_HDR_SIZE) : 4096;
        if (esp_partition_erase_range(p, off, 4096) != ESP_OK || esp_partition_write(p, off, jpeg + (off - IMG_HDR_SIZE), n) != ESP_OK) {
            return false;
        }
        vTaskDelay(pdMS_TO_TICKS(8));
    }
    img_hdr_t h = { .magic = IMG_MAGIC, .size = (uint32_t)len, .crc = crc, .w = SCR, .h = SCR };
    return esp_partition_write(p, 0, &h, sizeof h) == ESP_OK;
}

static void img_invalidate(void)
{
    const esp_partition_t *p = img_part();
    if (p) {
        esp_partition_erase_range(p, 0, IMG_HDR_SIZE);
    }
}

/* The stored picture into a PSRAM buffer (caller frees); NULL if there is none / it is damaged. */
static uint8_t *img_load(size_t *len_out, uint32_t expect_crc)
{
    const esp_partition_t *p = img_part();
    img_hdr_t h;
    if (!p || esp_partition_read(p, 0, &h, sizeof h) != ESP_OK || h.magic != IMG_MAGIC || h.size == 0 || h.size > IMG_MAX_BYTES ||
        h.size + IMG_HDR_SIZE > p->size || (expect_crc && h.crc != expect_crc)) {
        return NULL;
    }
    uint8_t *buf = heap_caps_malloc(h.size, MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT);
    if (!buf) {
        return NULL;
    }
    if (esp_partition_read(p, IMG_HDR_SIZE, buf, h.size) != ESP_OK || crc32_of(buf, h.size) != h.crc) {
        ESP_LOGW(TAG, "stored picture is damaged");
        heap_caps_free(buf);
        return NULL;
    }
    *len_out = h.size;
    return buf;
}

/* ---- pictures and backgrounds --------------------------------------------------------------------------------- */

static const uint8_t BAYER[4][4] = { { 0, 8, 2, 10 }, { 12, 4, 14, 6 }, { 3, 11, 1, 9 }, { 15, 7, 13, 5 } };

/* The companion's 480x480 baseline JPEG -> dithered RGB565 in PSRAM (so smooth, blurred areas do not band). NULL if unusable. */
static uint16_t *decode_photo(const uint8_t *jpeg, size_t len)
{
    uint8_t *rgb = heap_caps_aligned_alloc(64, RGB_BYTES, MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT);
    uint16_t *px = heap_caps_aligned_alloc(64, BG_BYTES, MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT);
    if (!rgb || !px) {
        ESP_LOGW(TAG, "no PSRAM to decode the picture");
        heap_caps_free(rgb);
        heap_caps_free(px);
        return NULL;
    }
    esp_jpeg_image_cfg_t cfg = {
        .indata = (uint8_t *)jpeg, .indata_size = (uint32_t)len, .outbuf = rgb, .outbuf_size = RGB_BYTES,
        .out_format = JPEG_IMAGE_FORMAT_RGB888, .out_scale = JPEG_IMAGE_SCALE_0,
    };
    esp_jpeg_image_output_t info = { 0 };
    esp_err_t err = esp_jpeg_get_image_info(&cfg, &info);
    if (err == ESP_OK && (info.width != SCR || info.height != SCR || info.output_len > RGB_BYTES)) {
        ESP_LOGW(TAG, "picture is %ux%u, expected %dx%d", (unsigned)info.width, (unsigned)info.height, SCR, SCR);
        err = ESP_ERR_INVALID_SIZE;
    }
    if (err == ESP_OK) {
        memset(&cfg.priv, 0, sizeof cfg.priv);
        err = esp_jpeg_decode(&cfg, &info);
    }
    if (err != ESP_OK) {
        ESP_LOGW(TAG, "picture decode failed: %s", esp_err_to_name(err));
        heap_caps_free(rgb);
        heap_caps_free(px);
        return NULL;
    }
    for (int y = 0; y < SCR; y++) {
        const uint8_t *p = rgb + (size_t)y * SCR * 3;
        uint16_t *out = px + (size_t)y * SCR;
        for (int x = 0; x < SCR; x++, p += 3) {
            int d = BAYER[y & 3][x & 3] * 2 - 15;
            int r = clampi(p[0] + ((d * 8) >> 5), 0, 255) >> 3;
            int g = clampi(p[1] + ((d * 4) >> 5), 0, 255) >> 2;
            int b = clampi(p[2] + ((d * 8) >> 5), 0, 255) >> 3;
            out[x] = (uint16_t)((r << 11) | (g << 5) | b);
        }
    }
    heap_caps_free(rgb);
    return px;
}

/* A dithered vertical gradient for the built-in themes (+ an accent-coloured glow along the bottom for Neon). */
static uint16_t *make_theme_bg(uint8_t theme, uint32_t accent)
{
    uint16_t *px = heap_caps_aligned_alloc(64, BG_BYTES, MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT);
    if (!px) {
        return NULL;
    }
    static const int TOP[3][3] = { { 6, 6, 9 }, { 29, 29, 54 }, { 16, 8, 42 } };
    static const int BOT[3][3] = { { 0, 0, 0 }, { 7, 7, 12 }, { 4, 3, 14 } };
    const int *top = TOP[theme > TH_NEON ? TH_DARK : theme], *bot = BOT[theme > TH_NEON ? TH_DARK : theme];
    const int ar = (accent >> 16) & 0xFF, ag = (accent >> 8) & 0xFF, ab = accent & 0xFF;
    for (int y = 0; y < SCR; y++) {
        const int t = y * 256 / (SCR - 1);
        int base[3];
        for (int c = 0; c < 3; c++) {
            base[c] = top[c] * (256 - t) + bot[c] * t;                       /* value * 256 */
        }
        const float dy = ((float)y - 520.0f) / 230.0f;
        for (int x = 0; x < SCR; x++) {
            int v[3] = { base[0], base[1], base[2] };
            if (theme == TH_NEON && y > 280) {
                const float dx = ((float)x - 240.0f) / 360.0f;
                const float d = sqrtf(dx * dx + dy * dy);
                if (d < 1.0f) {
                    const float g = (1.0f - d) * (1.0f - d) * 0.5f;
                    v[0] += (int)(ar * g * 256.0f);
                    v[1] += (int)(ag * g * 256.0f);
                    v[2] += (int)(ab * g * 256.0f);
                }
            }
            const int dth = BAYER[y & 3][x & 3] * 2 - 15;
            const int r = clampi(v[0] + dth * 64, 0, 65535) >> 11;
            const int g = clampi(v[1] + dth * 32, 0, 65535) >> 10;
            const int b = clampi(v[2] + dth * 64, 0, 65535) >> 11;
            px[y * SCR + x] = (uint16_t)((r << 11) | (g << 5) | b);
        }
    }
    return px;
}

static lv_image_dsc_t *next_dsc(const uint16_t *px)
{
    lv_image_dsc_t *d = &s.dsc[s.dsc_next];
    s.dsc_next = (s.dsc_next + 1) % 4;
    memset(d, 0, sizeof *d);
    d->header.magic = LV_IMAGE_HEADER_MAGIC;
    d->header.cf = LV_COLOR_FORMAT_RGB565;
    d->header.w = SCR;
    d->header.h = SCR;
    d->header.stride = SCR * 2;
    d->data_size = BG_BYTES;
    d->data = (const uint8_t *)px;
    return d;
}

/* ---- clock --------------------------------------------------------------------------------------------------- */

static void update_clock_text(void)
{
    int64_t base;
    portENTER_CRITICAL(&s.clock_mux);
    base = s.clock_base_ms;
    portEXIT_CRITICAL(&s.clock_mux);
    char txt[8] = "", dtxt[sizeof s.shown_date] = "";
    const char *ap = "";
    if (base != 0) {
        const int64_t local = base + now_ms();                /* the PC's local time: its own offset (time zone, daylight saving) is already in it */
        const int sec = (int)((local / 1000) % 86400);
        const int h = sec / 3600, m = (sec / 60) % 60;
        if (s.cfg.clock_24h) {
            snprintf(txt, sizeof txt, "%02d:%02d", h, m);
        } else {
            snprintf(txt, sizeof txt, "%d:%02d", h % 12 == 0 ? 12 : h % 12, m);
            ap = h < 12 ? "AM" : "PM";
        }
        if (s.cfg.show_date) {                                /* changes at local midnight with no help from the PC: the same running timer */
            idle_format_clock_date(dtxt, sizeof dtxt, local, s.cfg.date_fmt);
        }
    }
    if (strcmp(txt, s.shown_clock) != 0) {
        strlcpy(s.shown_clock, txt, sizeof s.shown_clock);
        lv_label_set_text(s.clock, txt);
        for (int i = 0; i < 4; i++) {
            lv_label_set_text(s.shadow[i], txt);
        }
        lv_label_set_text(s.ampm, ap);
        lv_obj_update_layout(s.clock);
        lv_obj_align_to(s.ampm, s.clock, LV_ALIGN_OUT_RIGHT_BOTTOM, 6, -(idle_font_clock.base_line - 8));
    }
    if (strcmp(dtxt, s.shown_date) != 0) {
        strlcpy(s.shown_date, dtxt, sizeof s.shown_date);
        lv_label_set_text(s.date, dtxt);
        for (int i = 0; i < 4; i++) {
            lv_label_set_text(s.dshadow[i], dtxt);
        }
    }
}

static void tick_cb(lv_timer_t *t)
{
    (void)t;
    update_clock_text();
}

